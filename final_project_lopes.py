def ScottifyWithStyles(target_Img_Name, styles=[0], should_save=False, savedName="output"):
    target_img = cv2.imread(target_Img_Name)

    target_img = cv2.cvtColor(target_img,cv2.COLOR_BGR2RGB)

    display(target_img)

    if styles == [-1]:
      styles = [int(x) for x in np.arange(3)]

    for idx in styles:
      source_faces = app.get(variations[idx])
      target_faces = app.get(target_img)

