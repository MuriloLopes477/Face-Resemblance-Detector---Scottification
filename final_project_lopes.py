def testModel(before_path,after_path, breakpoint=-1):
  ytest = []
  ypred = []

  i = 0

  for filename in os.listdir(before_path):
    if i == breakpoint:
      break

    i+=1

    ytest.append(0)

    img = cv2.imread(before_path + filename)
    img = cv2.resize(img, (img_width, img_height))
    img = np.expand_dims(img, axis=0)

    pred = model.predict(img)

    ypred.append(np.argmax(pred, axis=1)[0])

  i = 0

  for filename in os.listdir(after_path):
    if i == breakpoint:
      break

    i+=1

    ytest.append(1)

    img = cv2.imread(after_path + filename)
    img = cv2.resize(img, (img_width, img_height))
    img = np.expand_dims(img, axis=0)

    pred = model.predict(img)

    ypred.append(np.argmax(pred, axis=1)[0])

  class_names = ['Not Similar', 'Similar']

  print(classification_report(ytest, ypred))

  cm = confusion_matrix(ytest, ypred)
  print(cm)

  # Confusion matrix works better with color
  sns.heatmap(cm, square=True, annot=True, fmt='d', cbar=True,
                    cmap="YlGn",
                    xticklabels=class_names,
                    yticklabels=class_names)

  plt.xlabel('Predicted Label');
  plt.ylabel('True Label')
  plt.title('Confusion Matrix')
  plt.show()

